"""Managed HTTP proxy based on 3proxy."""
import re
import secrets
import shlex
import string


class HttpProxyManager:
    PROTOCOL = 'http_proxy'
    CONTAINER_NAME = 'http-proxy'
    IMAGE_NAME = '3proxy/3proxy:latest'
    CONFIG_DIR = '/opt/amnezia/http-proxy'
    CONFIG_PATH = '/etc/3proxy/3proxy.cfg'
    DEFAULT_PORT = 4769
    DEFAULT_USERNAME = 'bw'

    def __init__(self, ssh, protocol='http_proxy'):
        self.ssh = ssh
        self.protocol = protocol or self.PROTOCOL
        self.instance = self._instance_index(self.protocol)
        self.container_name = self._container_name(self.protocol)
        self.config_dir = self._config_dir(self.protocol)

    @staticmethod
    def _instance_index(protocol):
        try:
            return max(1, int(str(protocol or '').split('__', 1)[1]))
        except (IndexError, ValueError):
            return 1

    def _container_name(self, protocol=None):
        idx = self._instance_index(protocol or self.protocol)
        return self.CONTAINER_NAME if idx == 1 else f'{self.CONTAINER_NAME}-{idx}'

    def _config_dir(self, protocol=None):
        idx = self._instance_index(protocol or self.protocol)
        return self.CONFIG_DIR if idx == 1 else f'{self.CONFIG_DIR}-{idx}'

    @staticmethod
    def _valid_port(port):
        value = int(port)
        if not 1 <= value <= 65535:
            raise ValueError('Port must be between 1 and 65535')
        return value

    @staticmethod
    def _valid_username(username):
        value = str(username or '').strip()
        if not re.fullmatch(r'[A-Za-z0-9_.-]{1,64}', value):
            raise ValueError('Username may contain only letters, numbers, dot, underscore and hyphen')
        return value

    @staticmethod
    def _valid_password(password):
        value = str(password or '')
        if not value or len(value) > 128 or re.search(r'[\s:]', value) or any(ord(c) < 32 for c in value):
            raise ValueError('Password must be 1-128 characters without whitespace or colons')
        return value

    @staticmethod
    def _generate_password(length=18):
        alphabet = string.ascii_letters + string.digits
        return ''.join(secrets.choice(alphabet) for _ in range(length))

    def _build_config(self, username, password, port):
        return (
            '# 3proxy HTTP proxy — generated by Amnezia Web Panel\n'
            'nserver 8.8.8.8\n'
            'nserver 1.1.1.1\n'
            'nscache 65536\n'
            'nscache6 65536\n\n'
            'timeouts 1 5 30 60 180 1800 15 60\n'
            'maxconn 300\n'
            'flush\n\n'
            'auth strong\n'
            f'users {username}:CL:{password}\n'
            f'allow {username}\n'
            f'proxy -p{port}\n'
        )

    def _read_config(self):
        out, _, code = self.ssh.run_sudo_command(
            f'docker exec {shlex.quote(self.container_name)} cat {self.CONFIG_PATH} 2>/dev/null')
        if code != 0 or not out.strip():
            out, _, code = self.ssh.run_sudo_command(
                f'cat {shlex.quote(self.config_dir + "/3proxy.cfg")} 2>/dev/null')
        return out if code == 0 else ''

    def _parse_credentials(self, config):
        result = {'port': None, 'username': None, 'password': None}
        user = re.search(r'^\s*users\s+([^:\s]+):CL:(\S+)', config or '', re.M)
        port = re.search(r'^\s*proxy\s+-p(\d+)', config or '', re.M)
        if user:
            result.update(username=user.group(1), password=user.group(2))
        if port:
            result['port'] = int(port.group(1))
        return result

    def get_credentials(self):
        return self._parse_credentials(self._read_config())

    def check_docker_installed(self):
        out, _, code = self.ssh.run_command('docker --version 2>/dev/null')
        if code != 0 or not out.strip():
            return False
        status, _, _ = self.ssh.run_command('systemctl is-active docker 2>/dev/null')
        return status.strip().lower() == 'active'

    def check_protocol_installed(self, protocol_type='http_proxy'):
        name = self._container_name(protocol_type)
        state_fn = getattr(self.ssh, 'docker_container_state', None)
        if state_fn:
            state = state_fn(name)
            if state is not None:
                return state[0]
        out, _, _ = self.ssh.run_sudo_command(
            f'docker ps -a --filter name=^{name}$ --format "{{{{.Names}}}}"')
        return name in out.strip().splitlines()

    def check_container_running(self, protocol_type='http_proxy'):
        name = self._container_name(protocol_type)
        state_fn = getattr(self.ssh, 'docker_container_state', None)
        if state_fn:
            state = state_fn(name)
            if state is not None:
                return state[1]
        out, _, _ = self.ssh.run_sudo_command(
            f'docker ps --filter name=^{name}$ --format "{{{{.Status}}}}"')
        return 'Up' in out

    def get_server_status(self, protocol_type='http_proxy'):
        exists = self.check_protocol_installed(protocol_type)
        return {
            'container_exists': exists,
            'container_running': self.check_container_running(protocol_type),
            'protocol': protocol_type,
            'base_protocol': self.PROTOCOL,
            'instance': self._instance_index(protocol_type),
            'container_name': self._container_name(protocol_type),
            **(self.get_credentials() if exists else {}),
        }

    def _write_config(self, config):
        self.ssh.run_sudo_command(f'mkdir -p {shlex.quote(self.config_dir)}')
        self.ssh.upload_file_sudo(config, f'{self.config_dir}/3proxy.cfg')

    def _run_container(self, port):
        name = shlex.quote(self.container_name)
        directory = shlex.quote(self.config_dir)
        return self.ssh.run_sudo_command(
            f'docker rm -f {name} >/dev/null 2>&1 || true; '
            f'docker run -d --restart unless-stopped --name {name} '
            f'-p {port}:{port}/tcp '
            f'-v {directory}/3proxy.cfg:{self.CONFIG_PATH}:ro '
            f'--cap-drop ALL --security-opt no-new-privileges:true '
            f'--ulimit nofile=65536:65536 {self.IMAGE_NAME}')

    def install_protocol(self, protocol_type='http_proxy', port=None, username=None, password=None):
        if not self.check_docker_installed():
            return {'status': 'error', 'message': 'Docker is not installed or not running'}
        port = self._valid_port(port or self.DEFAULT_PORT)
        username = self._valid_username(username or self.DEFAULT_USERNAME)
        password = self._valid_password(password or self._generate_password())
        _, err, code = self.ssh.run_sudo_command(f'docker pull {self.IMAGE_NAME}')
        if code != 0:
            return {'status': 'error', 'message': err or 'Failed to pull 3proxy image'}
        self._write_config(self._build_config(username, password, port))
        _, err, code = self._run_container(port)
        if code != 0:
            return {'status': 'error', 'message': err or 'Failed to start HTTP proxy container'}
        return {
            'status': 'success', 'protocol': protocol_type, 'base_protocol': self.PROTOCOL,
            'container_name': self.container_name, 'port': port, 'username': username,
            'password': password, 'message': 'HTTP proxy installed',
            'log': [f'HTTP proxy listening on TCP port {port}',
                    f'Username: {username}', 'Password saved in panel settings'],
        }

    def update_credentials(self, port=None, username=None, password=None):
        if not self.check_protocol_installed(self.protocol):
            return {'status': 'error', 'message': 'HTTP proxy is not installed'}
        current = self.get_credentials()
        new_port = self._valid_port(port if port is not None else (current.get('port') or self.DEFAULT_PORT))
        new_user = self._valid_username(username if username is not None else (current.get('username') or self.DEFAULT_USERNAME))
        new_pass = self._valid_password(password if password else (current.get('password') or self._generate_password()))
        self._write_config(self._build_config(new_user, new_pass, new_port))
        if current.get('port') != new_port:
            _, err, code = self._run_container(new_port)
        else:
            _, err, code = self.ssh.run_sudo_command(f'docker restart {shlex.quote(self.container_name)}')
        if code != 0:
            return {'status': 'error', 'message': err or 'Failed to apply HTTP proxy settings'}
        return {'status': 'success', 'port': new_port, 'username': new_user, 'password': new_pass}

    def remove_container(self, protocol_type='http_proxy'):
        name = shlex.quote(self._container_name(protocol_type))
        directory = shlex.quote(self._config_dir(protocol_type))
        self.ssh.run_sudo_command(f'docker stop {name} >/dev/null 2>&1 || true')
        self.ssh.run_sudo_command(f'docker rm -fv {name} >/dev/null 2>&1 || true')
        self.ssh.run_sudo_command(f'rm -rf {directory}')
        return True
